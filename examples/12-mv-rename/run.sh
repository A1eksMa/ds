#!/usr/bin/env bash
# `ds mv --src SRC --lb OLD --to-lb NEW`: источник переименовал показатель
# "Изготовитель" в "Производитель". Батч 2 уже пришёл под новым именем для клиента 102
# (переходный период), пока клиент 101 ещё числится только под старым. `ds mv` сводит
# обе метки в одну: клиент 101 получает "Производитель" впервые (унаследовав старое
# значение), клиент 102 — уже имел запись под новым именем, она не трогается (более
# новая транзакция побеждает при свёртке), просто в тот же `lb_id` добавляется более
# старая история из "Изготовитель". Старая метка после переноса исчезает из пула.
# Использование:  bash run.sh [WORKDIR]   (env DS — переопределение команды)
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO="$(cd "$HERE/../.." && pwd)"
WORK="${1:-$(mktemp -d)}"
DB="$WORK/data.db"
DS="${DS:-python3 -m src.cli.commands}"

cd "$REPO"
export PYTHONPATH="$REPO"
echo "workdir: $WORK" >&2

$DS --db "$DB" load "$HERE/sources/CRM" "$HERE/batch1.json" --dt 1704067200
$DS --db "$DB" load "$HERE/sources/CRM" "$HERE/batch2.json" --dt 1706745600

echo "--- ds get: обе метки существуют параллельно (переходный период) ---"
$DS --db "$DB" get --dt 1706745600 --src CRM

echo "--- ds mv --src CRM --lb Изготовитель --to-lb Производитель --yes ---"
$DS --db "$DB" mv --src CRM --lb "Изготовитель" --to-lb "Производитель" --yes

echo "--- ds get: одна метка на двоих, у 102 сохранилось более новое значение ---"
$DS --db "$DB" get --dt 1706745600 --src CRM
